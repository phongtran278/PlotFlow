import fs from "node:fs";
import path from "node:path";
import { pathToFileURL, fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const appDir = path.resolve(__dirname, "..");
const projectDir = path.resolve(appDir, "..");
const catalogPath = path.join(appDir, "src", "data", "generatedHouseCatalog.js");
const optimizedDir = path.join(projectDir, "assets", "houses_optimized");

if (!fs.existsSync(catalogPath) || !fs.existsSync(optimizedDir)) process.exit(0);

const moduleUrl = `${pathToFileURL(catalogPath).href}?t=${Date.now()}`;
const { generatedHouseCatalog = [] } = await import(moduleUrl);
const optimizedNames = new Set(fs.readdirSync(optimizedDir));

const rows = generatedHouseCatalog.map((item) => {
  const stem = String(item.fileName || "").replace(/\.[^.]+$/, "");
  const optimizedName = `${stem}.webp`;
  if (!optimizedNames.has(optimizedName)) return item;
  return {
    ...item,
    originalSrc: item.src,
    src: `/assets/houses_optimized/${encodeURIComponent(optimizedName)}`,
    optimized: true,
  };
});

const content = `// Auto-generated by app/tools/sync-assets.mjs + apply-optimized-assets.mjs.\nexport const generatedHouseCatalog = ${JSON.stringify(rows, null, 2)};\n`;
fs.writeFileSync(catalogPath, content, "utf8");
console.log(`✓ Runtime house catalog: ${rows.filter((item) => item.optimized).length}/${rows.length} optimized`);
